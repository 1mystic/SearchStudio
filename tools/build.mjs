// node tools/build.mjs [--watch] [--no-test]
// Scans algorithms/ and examples/, validates them, and writes:
//   src/generated/data.js        examples + stylesheet text (used by exports)
//   algorithms/manifest.json     what the library contains
//   index.html                   the site, loading every file from the folders (dev / GitHub Pages)
//   dist/search-studio.html      the whole site in one file (offline, email, hosting anywhere)
//   dist/artifact.html           the same, without the document skeleton (for claude.ai Artifacts)
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, CORE, loadStudio, listAlgorithmFiles, listExampleFiles, listTypeFiles } from "./load.mjs";
import * as SEO from "./seo.mjs";

const args = new Set(process.argv.slice(2));
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const SITE = (process.env.SITE_URL || PKG.homepage || "https://1mystic.github.io/search-studio/").replace(/\/?$/, "/");
const UI = ["src/ui/render.js", "src/ui/app.js"];
const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const write = (f, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, f)), { recursive: true }); fs.writeFileSync(path.join(ROOT, f), s); };

function build() {
  const t0 = Date.now();
  const { Studio, errors, owner } = loadStudio();
  if (errors.length) { console.error("✗ build stopped:\n  " + errors.join("\n  ")); return false; }
  if (!args.has("--no-test")) {
    try { execFileSync(process.execPath, [path.join(ROOT, "tools/test.mjs")], { stdio: "pipe" }); }
    catch (e) { console.error("✗ tests failed:\n" + String(e.stdout || e.message).split("\n").filter(l => /FAIL/.test(l)).slice(0, 20).join("\n")); return false; }
  }
  const css = read("src/styles/studio.css");
  const examples = listExampleFiles().map(f => JSON.parse(read(f)));
  const files = Object.fromEntries(Object.entries(owner).map(([id, f]) => [id, f.replace(/\\/g, "/")]));
  const data = `/* generated by tools/build.mjs — do not edit */\n(function(){ const S = window.Studio;\n${examples.map(e => `S.registerExample(${JSON.stringify(e)});`).join("\n")}\nS.CSS = ${JSON.stringify(css)};\nS.files = ${JSON.stringify(files)};\nS.SITE = ${JSON.stringify(SITE)};\n})();\n`;
  write("src/generated/data.js", data);
  const algoFiles = listAlgorithmFiles();
  const manifest = {
    generated: new Date().toISOString(),
    algorithms: Studio.algorithms.map(a => ({ id: a.id, name: a.name, family: a.family, problem: a.problem, file: owner[a.id], summary: a.summary })),
    examples: examples.map(e => ({ id: e.id, name: e.name, type: e.type })),
    problemTypes: Object.values(Studio.types).map(t => ({ type: t.type, label: t.label })),
  };
  write("algorithms/manifest.json", JSON.stringify(manifest, null, 1));

  let tpl = read("src/index.template.html");
  for (const page of ["home", "guide", "about", "contribute"]) tpl = tpl.replace(`<!--PAGE:${page}-->`, () => read(`src/pages/${page}.html`));
  tpl = tpl.replaceAll("<!--COUNT-->", () => String(Studio.algorithms.length));
  const seo = SEO.build(Studio, owner, SITE, PKG);
  const scriptFiles = [...CORE, ...listTypeFiles(), "src/generated/data.js", ...algoFiles, ...UI];
  // the template is page content; for the real documents everything before the skip link belongs in <head>
  const split = t => { const i = t.indexOf('<a class="skip"'); return [t.slice(0, i), t.slice(i)]; };
  const doc = (head, body) => `<!doctype html>\n<html lang="en" data-theme="dark">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n${head}</head>\n<body>\n${body}\n</body>\n</html>\n`;

  // multi-file site (GitHub Pages): full SEO head, crawlable fallback, static learn pages, sitemap, robots, llms.txt
  const dev = tpl.replace("<!--SEO-->", () => seo.head).replace("<!--NOSCRIPT-->", () => seo.noscript)
                 .replace("<!--STYLES-->", () => `<link rel="stylesheet" href="src/styles/studio.css">`)
                 .replace("<!--SCRIPTS-->", () => scriptFiles.map(f => `<script src="${f}"></script>`).join("\n"));
  const [dh, db] = split(dev);
  write("index.html", doc(dh, `<!-- generated by tools/build.mjs from src/index.template.html — edit the template, not this file -->\n${db}`));
  for (const [f, html] of Object.entries(seo.files)) write(f, html);

  // single file (offline) and artifact (no skeleton, no canonical: it is a copy)
  const inline = tpl.replace("<!--NOSCRIPT-->", () => seo.noscript)
                    .replace("<!--STYLES-->", () => `<style>\n${css}\n</style>`)
                    .replace("<!--SCRIPTS-->", () => scriptFiles.map(f => `<script>/* ${f} */\n${read(f).replace(/<\/script/gi, "<\\/script")}\n</script>`).join("\n"));
  write("dist/artifact.html", inline.replace("<!--SEO-->", () => seo.meta));
  const [ih, ib] = split(inline.replace("<!--SEO-->", () => seo.meta));
  write("dist/search-studio.html", doc(ih, ib));
  console.log(`✓ ${Studio.algorithms.length} algorithms, ${examples.length} examples → index.html, dist/search-studio.html (${Math.round(fs.statSync(path.join(ROOT, "dist/search-studio.html")).size / 1024)} KB) in ${Date.now() - t0} ms`);
  return true;
}

const ok = build();
if (args.has("--watch")) {
  console.log("watching algorithms/, examples/ and src/ …");
  let t = null;
  for (const dir of ["algorithms", "examples", "src", "problem-types"]) {
    fs.watch(path.join(ROOT, dir), { recursive: true }, (ev, file) => {
      if (!file || file.includes("generated") || file.endsWith("manifest.json")) return;
      clearTimeout(t); t = setTimeout(() => { console.log(`changed: ${dir}/${file}`); build(); }, 200);
    });
  }
} else if (!ok) process.exit(1);
